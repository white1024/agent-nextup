const saved =
  typeof localStorage !== "undefined" ? localStorage.getItem("nextup-lang") : null;

void i18n.use(initReactI18next).init({
  resources: {
    "zh-TW": { translation: zhTW },
    en: { translation: en },
  },
  // English is the default for a fresh install; zh-TW stays fully supported
  // and is one click away in Settings. An existing install is unaffected —
  // `saved` wins, so anyone who already picked a language keeps it.
  lng: saved ?? "en",
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

/**
 * Keep `<html lang>` in step with the active language (D65).
 *
 * `index.html` has always shipped `lang="zh-TW"`, but nothing ever updated it
 * — so in English the document still claimed to be Chinese. Two things depend
 * on it being right. Assistive tech picks pronunciation from it. And
 * `styles.css` sizes the few genuinely locale-sensitive tracks off `:lang()`:
 * English relative times run to "59 minutes ago" where zh-TW tops out at
 * "59 分鐘前", and the event row's time column is a fixed grid track (each row
 * is its own grid, so `max-content` would leave the rows ragged).
 */
function syncDocumentLang(lang: string) {
  if (typeof document !== "undefined") document.documentElement.lang = lang;
}

syncDocumentLang(i18n.language);
i18n.on("languageChanged", syncDocumentLang);

export function setLanguage(lang: "zh-TW" | "en") {
  void i18n.changeLanguage(lang);
  localStorage.setItem("nextup-lang", lang);
}

export default i18n;
